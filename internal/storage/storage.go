// Package storage holds the file library's rules: where bytes live, what a
// stored file is allowed to be, and how identity is established so that two
// identical uploads do not become two copies.
//
// It deliberately knows nothing about PocketBase records. The panel binds these
// primitives to collections; the primitives themselves are pure and testable.
package storage

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"image"
	// The decoders register themselves; measuring a PNG or JPEG needs them
	// imported even though they are not named.
	_ "image/gif"
	_ "image/jpeg"
	_ "image/png"
	"io"
	"net/http"
	"os"
	"path"
	"path/filepath"
	"strings"
)

// Driver stores and retrieves file bytes.
//
// The object-store driver belongs to the integrations module; this interface is
// the seam it will implement. Nothing above it may assume a filesystem.
type Driver interface {
	// Save writes the contents of r under key and reports how many bytes it wrote.
	Save(key string, r io.Reader) (int64, error)

	// Open returns the bytes stored under key.
	Open(key string) (io.ReadCloser, error)

	// Delete removes key. Removing a key that is not present is not an error, so
	// a retried delete converges instead of failing.
	Delete(key string) error

	// Exists reports whether key is present.
	Exists(key string) (bool, error)

	// Name identifies the driver, and is recorded on each file row so a future
	// migration can tell where a record's bytes actually are.
	Name() string
}

// LocalDriver stores bytes under a root directory on the filesystem.
type LocalDriver struct {
	root string
}

// NewLocalDriver returns a driver rooted at dir, creating it if needed.
func NewLocalDriver(dir string) (*LocalDriver, error) {
	if dir == "" {
		return nil, errors.New("storage: a local driver needs a root directory")
	}
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return nil, fmt.Errorf("storage: create root %q: %w", dir, err)
	}
	return &LocalDriver{root: dir}, nil
}

// Name implements Driver.
func (d *LocalDriver) Name() string { return "local" }

// Save implements Driver.
func (d *LocalDriver) Save(key string, r io.Reader) (int64, error) {
	full, err := d.resolve(key)
	if err != nil {
		return 0, err
	}
	if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
		return 0, fmt.Errorf("storage: create parent for %q: %w", key, err)
	}

	// Write to a temporary file and rename, so a reader never observes a partial
	// file and an interrupted upload leaves no half-stored object behind.
	tmp, err := os.CreateTemp(filepath.Dir(full), ".upload-*")
	if err != nil {
		return 0, fmt.Errorf("storage: temp file: %w", err)
	}
	tmpName := tmp.Name()

	written, err := io.Copy(tmp, r)
	closeErr := tmp.Close()
	if err == nil {
		err = closeErr
	}
	if err != nil {
		_ = os.Remove(tmpName)
		return 0, fmt.Errorf("storage: write %q: %w", key, err)
	}

	if err := os.Chmod(tmpName, 0o640); err != nil {
		_ = os.Remove(tmpName)
		return 0, fmt.Errorf("storage: chmod %q: %w", key, err)
	}
	if err := os.Rename(tmpName, full); err != nil {
		_ = os.Remove(tmpName)
		return 0, fmt.Errorf("storage: commit %q: %w", key, err)
	}

	return written, nil
}

// Open implements Driver.
func (d *LocalDriver) Open(key string) (io.ReadCloser, error) {
	full, err := d.resolve(key)
	if err != nil {
		return nil, err
	}
	f, err := os.Open(full)
	if err != nil {
		return nil, fmt.Errorf("storage: open %q: %w", key, err)
	}
	return f, nil
}

// Delete implements Driver.
func (d *LocalDriver) Delete(key string) error {
	full, err := d.resolve(key)
	if err != nil {
		return err
	}
	if err := os.Remove(full); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("storage: delete %q: %w", key, err)
	}
	return nil
}

// Exists implements Driver.
func (d *LocalDriver) Exists(key string) (bool, error) {
	full, err := d.resolve(key)
	if err != nil {
		return false, err
	}
	if _, err := os.Stat(full); err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, err
	}
	return true, nil
}

// resolve turns a storage key into an absolute path, refusing anything that is
// not already a clean relative key.
//
// Keys are generated by this package from a content hash, so a valid key never
// needs normalising. That makes "reject anything unclean" both stricter and
// safer than "clean it and carry on": cleaning turns "../x" into "x", which stays
// inside the root but silently addresses a different object than the caller
// named. Aliasing of that kind is a correctness bug even when it is not a
// traversal, and the cost of being wrong here is reading or writing an arbitrary
// file on the host.
func (d *LocalDriver) resolve(key string) (string, error) {
	if key == "" {
		return "", errors.New("storage: empty key")
	}
	if strings.ContainsRune(key, 0) {
		return "", errors.New("storage: key contains a null byte")
	}
	// A backslash is a literal character on this platform and a separator on
	// Windows; refusing it means the guarantee does not depend on which one the
	// binary was built for.
	if strings.ContainsRune(key, '\\') {
		return "", fmt.Errorf("storage: key %q contains a backslash", key)
	}
	if strings.HasPrefix(key, "/") {
		return "", fmt.Errorf("storage: key %q is absolute", key)
	}
	if path.Clean(key) != key {
		return "", fmt.Errorf("storage: key %q is not a clean relative path", key)
	}

	full := filepath.Join(d.root, filepath.FromSlash(key))

	// Belt and braces: after joining, the result must still be inside the root.
	rel, err := filepath.Rel(d.root, full)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("storage: key %q escapes the root", key)
	}

	return full, nil
}

// Policy is the upload policy: what may be stored at all.
type Policy struct {
	// AllowedExtensions is an allow-list matched against the extension derived
	// from the sniffed content type, never against the client's file name.
	AllowedExtensions []string

	// MaxSize is the largest accepted upload in bytes. Zero means no limit.
	MaxSize int64

	// MaxImageWidth and MaxImageHeight reject an image larger than the bound.
	// Zero disables the check. They are not a substitute for a size limit: a
	// highly compressed image can be enormous in pixels and small in bytes, and
	// decoding it is what costs memory.
	MaxImageWidth  int
	MaxImageHeight int
}

// DefaultPolicy is used until the settings module supplies configured values.
//
// Per D-012 in docs/decisions.md, storage is wave 2 and the settings module that
// owns these values is wave 3, so the seam exists now and the caller fills it
// later. The defaults are deliberately conservative: an allow-list of types that
// are safe to serve back, and a size cap.
func DefaultPolicy() Policy {
	return Policy{
		AllowedExtensions: []string{
			".jpg", ".jpeg", ".png", ".gif", ".webp", ".svg",
			".pdf", ".txt", ".md", ".csv",
			".doc", ".docx", ".xls", ".xlsx", ".ppt", ".pptx",
			".zip", ".gz",
		},
		MaxSize: 32 << 20, // 32 MiB
	}
}

// AllowsImage reports whether an image's dimensions are within the bounds.
//
// A non-image, or an image whose dimensions could not be read, is allowed: the
// type check has already decided the file may be stored, and refusing an image
// because its header could not be parsed would reject valid files from a format
// this build does not decode.
func (p Policy) AllowsImage(inspected Inspected) bool {
	if inspected.Kind != "image" || inspected.Width == 0 || inspected.Height == 0 {
		return true
	}
	if p.MaxImageWidth > 0 && inspected.Width > p.MaxImageWidth {
		return false
	}
	if p.MaxImageHeight > 0 && inspected.Height > p.MaxImageHeight {
		return false
	}
	return true
}

// Allows reports whether an extension is permitted.
func (p Policy) Allows(extension string) bool {
	extension = strings.ToLower(extension)
	for _, allowed := range p.AllowedExtensions {
		if strings.ToLower(allowed) == extension {
			return true
		}
	}
	return false
}

// Inspected is what was learned about an upload by reading it.
type Inspected struct {
	// MimeType is sniffed from the bytes, never taken from the client.
	MimeType string

	// Extension is derived from the sniffed type, so a file cannot claim one
	// format and be served as another.
	Extension string

	// Checksum is the SHA-256 of the content, in hex.
	Checksum string

	// Size is the number of bytes.
	Size int64

	// Kind is the coarse library tag: image, document, archive, video, audio or
	// other.
	Kind string

	// Width and Height are set for an image whose header could be read, and zero
	// otherwise. Only the formats the standard library decodes are measured.
	Width  int
	Height int
}

// Inspect reads a stream, computes its checksum, and decides what it is.
//
// The whole stream is consumed: the checksum is the file's identity and the size
// is recorded, so both have to see every byte. The sniffed type comes from the
// first 512 bytes, which is all DetectContentType looks at.
func Inspect(r io.Reader) (Inspected, error) {
	hash := sha256.New()
	tee := io.TeeReader(r, hash)

	head := make([]byte, 512)
	n, err := io.ReadFull(tee, head)
	if err != nil && !errors.Is(err, io.EOF) && !errors.Is(err, io.ErrUnexpectedEOF) {
		return Inspected{}, fmt.Errorf("storage: read the upload: %w", err)
	}
	head = head[:n]

	// Everything after the sniffed head still has to be hashed and counted.
	rest, err := io.Copy(io.Discard, tee)
	if err != nil {
		return Inspected{}, fmt.Errorf("storage: read the upload: %w", err)
	}

	mimeType := http.DetectContentType(head)
	extension := ExtensionFor(mimeType)

	width, height := imageDimensions(mimeType, head)

	return Inspected{
		MimeType:  mimeType,
		Extension: extension,
		Checksum:  hex.EncodeToString(hash.Sum(nil)),
		Size:      int64(n) + rest,
		Kind:      KindFor(mimeType),
		Width:     width,
		Height:    height,
	}, nil
}

// imageDimensions reads an image's size from its header.
//
// Only the formats the standard library decodes are measured, which is why the
// result is advisory: the caller applies a bound when it has one and skips the
// check when it does not. The header is all DecodeConfig reads, so an enormous
// image is not decoded to measure it -- the size is taken from the head that was
// read anyway.
func imageDimensions(mimeType string, head []byte) (int, int) {
	if !strings.HasPrefix(mimeType, "image/") {
		return 0, 0
	}
	// The standard library has no WebP decoder and an SVG has no pixel size, so
	// both report zero and are skipped by the bound.
	switch mimeType {
	case "image/png", "image/jpeg", "image/gif":
	default:
		return 0, 0
	}

	cfg, _, err := image.DecodeConfig(bytes.NewReader(head))
	if err != nil {
		return 0, 0
	}
	return cfg.Width, cfg.Height
}

// extensionByMime maps a sniffed content type to a stored extension.
//
// Only types this platform will serve back are listed. Anything absent gets no
// extension, which means the policy rejects it -- a deniable default rather than
// a permissive one.
var extensionByMime = map[string]string{
	"image/jpeg":    ".jpg",
	"image/png":     ".png",
	"image/gif":     ".gif",
	"image/webp":    ".webp",
	"image/svg+xml": ".svg",

	"application/pdf": ".pdf",
	"text/plain":      ".txt",
	"text/markdown":   ".md",
	"text/csv":        ".csv",
	"text/html":       ".html",

	"application/zip":    ".zip",
	"application/gzip":   ".gz",
	"application/x-gzip": ".gz",
	"application/x-tar":  ".tar",
	"application/msword": ".doc",
	"application/vnd.openxmlformats-officedocument.wordprocessingml.document": ".docx",
	"application/vnd.ms-excel": ".xls",
	"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet":         ".xlsx",
	"application/vnd.ms-powerpoint":                                             ".ppt",
	"application/vnd.openxmlformats-officedocument.presentationml.presentation": ".pptx",

	"video/mp4":  ".mp4",
	"audio/mpeg": ".mp3",
	"audio/ogg":  ".ogg",
}

// ExtensionFor returns the stored extension for a sniffed content type, or "".
func ExtensionFor(mimeType string) string {
	// DetectContentType may append parameters; the type alone decides.
	if i := strings.IndexByte(mimeType, ';'); i >= 0 {
		mimeType = strings.TrimSpace(mimeType[:i])
	}
	return extensionByMime[strings.ToLower(mimeType)]
}

// KindFor returns the coarse library tag for a sniffed content type.
func KindFor(mimeType string) string {
	if i := strings.IndexByte(mimeType, ';'); i >= 0 {
		mimeType = strings.TrimSpace(mimeType[:i])
	}
	mimeType = strings.ToLower(mimeType)

	switch {
	case strings.HasPrefix(mimeType, "image/"):
		return "image"
	case strings.HasPrefix(mimeType, "video/"):
		return "video"
	case strings.HasPrefix(mimeType, "audio/"):
		return "audio"
	case mimeType == "application/zip", mimeType == "application/gzip",
		mimeType == "application/x-gzip", mimeType == "application/x-tar":
		return "archive"
	case strings.HasPrefix(mimeType, "text/"),
		mimeType == "application/pdf",
		strings.Contains(mimeType, "word"),
		strings.Contains(mimeType, "excel"),
		strings.Contains(mimeType, "spreadsheet"),
		strings.Contains(mimeType, "powerpoint"),
		strings.Contains(mimeType, "presentation"):
		return "document"
	default:
		return "other"
	}
}

// Key returns the storage key for a checksum.
//
// The key is derived from the content, which is what makes deduplication free:
// two uploads of the same bytes compute the same key and therefore address the
// same object, so the second one writes nothing. It also means deleting one file
// row cannot destroy another's bytes by accident -- the caller must check whether
// any other row still addresses the key before removing it.
//
// The key is sharded by the first two hex characters so a directory does not
// accumulate every object in the library.
func Key(checksum string) string {
	if len(checksum) < 4 {
		return "objects/" + checksum
	}
	return "objects/" + checksum[0:2] + "/" + checksum[2:4] + "/" + checksum
}

// SafeName reduces a client-supplied file name to something safe to store as a
// display label.
//
// It is never used to build a storage key -- the key comes from the checksum --
// but it is recorded and rendered, so directory separators, control characters
// and leading dots are stripped rather than trusted.
func SafeName(name string) string {
	name = strings.ReplaceAll(name, "\\", "/")
	name = path.Base(name)
	name = strings.Map(func(r rune) rune {
		if r < 0x20 || r == 0x7f {
			return -1
		}
		return r
	}, name)
	name = strings.TrimSpace(strings.TrimLeft(name, "."))

	if name == "" {
		return "unnamed"
	}
	if len(name) > 200 {
		// Keep the extension, which is what a reader uses to identify the file.
		if ext := path.Ext(name); len(ext) < 20 {
			name = name[:200-len(ext)] + ext
		} else {
			name = name[:200]
		}
	}
	return name
}
